"""The agent rules say docs/INDEX.md is generated: the reviewer never flags its diff, the dev never edits it by hand."""

import os
import unittest

AGENTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "agents")

REVIEWER_SENTENCE = "A `docs/INDEX.md` diff is generated by `wt.py commit`: never out of scope, never a finding."
DEV_SENTENCE = "Do not edit `docs/INDEX.md` by hand: `wt.py commit` regenerates it, so a diff there is expected."


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


class IndexRule(unittest.TestCase):
    def test_reviewer_never_flags_the_generated_index_diff(self):
        text = read(os.path.join(AGENTS, "reviewer", "rare-rules.md"))
        self.assertIn(REVIEWER_SENTENCE, text)

    def test_dev_never_edits_the_generated_index_by_hand(self):
        text = read(os.path.join(AGENTS, "dev", "rare-rules.md"))
        self.assertIn(DEV_SENTENCE, text)


if __name__ == "__main__":
    unittest.main()
