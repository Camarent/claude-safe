"""Whole-docs cite check at every stage end: steps_finaltest.py --doc-cites and the step phases.audit_phases plans (docs_cite_final)."""

import os
import sys
import tempfile
import unittest
from types import SimpleNamespace
from unittest import mock

os.environ["PIPELINE_NO_LEADS"] = "1"
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from pipeline import phases, steps_finaltest
from pipeline.configuration import DOC_CITES_FLAG, DOC_CITES_KEY, DOC_CITES_STEP, DONE, FAIL

CFG = {"docs_dir": "docs"}
SOURCE = "def alpha():\n    return 1\n\n\ndef beta():\n    return 2\n"


class _Repo(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.repo = tmp.name
        self.write("src/mod.py", SOURCE)

    def write(self, rel, text):
        path = os.path.join(self.repo, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


class DocCitesTest(_Repo):
    def test_cite_past_the_file_end_fails_and_names_doc_and_line(self):
        self.write("docs/guide.md", "# Guide\n\nSee `src/mod.py:99` for it.\n")
        verdict, msgs = steps_finaltest.doc_cites(CFG, self.repo)
        self.assertEqual(verdict, FAIL)
        self.assertEqual(len(msgs), 1)
        self.assertIn("docs/guide.md:3", msgs[0])
        self.assertIn("src/mod.py:99", msgs[0])

    def test_good_cite_passes(self):
        self.write("docs/guide.md", "# Guide\n\nSee `src/mod.py:5` for it.\n")
        self.assertEqual(steps_finaltest.doc_cites(CFG, self.repo), (DONE, []))

    def test_bad_cite_in_a_fenced_block_does_not_fail(self):
        self.write("docs/guide.md", "# Guide\n\n```\nsee src/mod.py:99\n```\n")
        self.assertEqual(steps_finaltest.doc_cites(CFG, self.repo), (DONE, []))

    def test_bad_cite_in_a_generated_doc_does_not_fail(self):
        self.write("docs/index.md", "<!-- Generated by build.py - do not edit -->\nsee src/mod.py:99\n")
        self.assertEqual(steps_finaltest.doc_cites(CFG, self.repo), (DONE, []))

    def test_doc_the_stage_did_not_change_is_still_checked(self):
        # no git repo here: the check reads the whole docs folder, not a diff
        self.write("docs/background.md", "Background: `src/mod.py:99`.\n")
        verdict, msgs = steps_finaltest.doc_cites(CFG, self.repo)
        self.assertEqual(verdict, FAIL)
        self.assertIn("docs/background.md:1", msgs[0])

    def test_no_docs_folder_is_done(self):
        self.assertEqual(steps_finaltest.doc_cites(CFG, self.repo), (DONE, []))

    def test_main_prints_verdict_without_report(self):
        self.write("docs/guide.md", "See `src/mod.py:99`.\n")
        with (
            mock.patch.object(steps_finaltest, "project", return_value=CFG),
            mock.patch.object(steps_finaltest, "repo_dir", return_value=self.repo),
            mock.patch("builtins.print") as pr,
        ):
            self.assertEqual(steps_finaltest.main(["--dir", self.repo, DOC_CITES_FLAG]), 0)
        printed = pr.call_args[0][0]
        self.assertTrue(printed.startswith(f"VERDICT: {FAIL}\n"))
        self.assertIn("docs/guide.md:1", printed)


class PlannedStepTest(_Repo):
    def steps(self, cfg, flags):
        a = SimpleNamespace(stage="s1", dir=self.repo)
        with mock.patch.object(phases, "project", return_value=cfg):
            return [s for batch in phases.audit_phases(a, flags, [], []) for s in batch if s["id"] == DOC_CITES_STEP]

    def test_setting_false_plans_no_step(self):
        self.assertEqual(self.steps({DOC_CITES_KEY: False}, {"test": False, "docs": False, "audit": False}), [])

    def test_step_is_planned_with_the_docs_flag_off(self):
        found = self.steps({}, {"test": False, "docs": False, "audit": False})
        self.assertEqual(len(found), 1)
        self.assertIn(DOC_CITES_FLAG, found[0]["prompt"])
        self.assertEqual(found[0]["agent"], "script")

    def test_cite_step_is_satisfied_only_by_done(self):
        # steps.py treats any verdict in step["ok"] as satisfied: a FAIL cite report must not pass the step
        found = self.steps({}, {"test": False, "docs": False, "audit": False})
        self.assertEqual(found[0]["ok"], {DONE})
        self.assertNotIn(FAIL, found[0]["ok"])

    def test_cite_step_follows_the_beside_docs_writer_batch(self):
        # docs_beside_audits: the docs writer rides in the first audit batch, so the cite step must come after that batch
        a = SimpleNamespace(stage="s1", dir=self.repo)

        def fake_rounds(*args):  # (a, cfg, flags, tasks, evs, beside)
            yield [*args[5], {"id": "audit-1", "agent": "audit"}]

        flags = {"test": False, "docs": True, "audit": True}
        with (
            mock.patch.object(phases, "project", return_value=CFG),
            mock.patch.object(phases, "audit_dir_of", return_value=self.repo),
            mock.patch.object(phases, "paths", return_value=(self.repo,)),
            mock.patch.object(phases, "audit_due", return_value=True),
            mock.patch.object(phases, "docs_beside_audits", return_value=True),
            mock.patch.object(phases, "audit_rounds", side_effect=fake_rounds),
        ):
            batches = list(phases.audit_phases(a, flags, [], []))
        ids = [[s["id"] for s in batch] for batch in batches]
        docs_at = next(i for i, ids_in in enumerate(ids) if "final-docs" in ids_in)
        cites_at = next(i for i, ids_in in enumerate(ids) if DOC_CITES_STEP in ids_in)
        self.assertGreater(cites_at, docs_at)
        self.assertEqual(ids[cites_at], [DOC_CITES_STEP])


if __name__ == "__main__":
    unittest.main()
