"""Command/path index: loads `<home>/paths.json` and generates the `cs-*` sh wrappers.

The index holds the only paths that differ between host and container (`roots`) and every command the agents may call (`commands`).
A wrapper finds the pipeline home from its own location, so it holds no path; when its target is missing it exits 2 (a hook or a
guard that runs through it then blocks instead of failing open with 127).

    python3 -I tools/cmdindex.py gen-bin [--check]
    python3 -I tools/cmdindex.py check-path --settings FILE [--bin DIR]   (container start-up check)
"""

import argparse
import json
import os
import re
import shlex
import stat
import subprocess
import sys

from pipeline import cmdnames
from pipeline.cmdnames import DEFAULT_SIDE, INDEX_NAME, command_name, commands, names_for, side_of  # noqa: F401  # re-exports: the public index API
from pipeline.configuration import HOME
from pipeline.util import write_text

BIN_DIRS = {"container": "bin", "host": "bin-host"}  # wrapper folders under the home; only `bin` is mounted on PATH in the container
SIDES = ("host", "container", "both")
DEFAULT_RUNNER = "python3 -I"
BASE_HOME = "home"
BASE_REPO = "repo"
EXIT_MISSING = 2  # wrapper exit code for an unresolvable target
HOME_MARK = "@home"  # a root value meaning "the real pipeline home"
REF_PREFIX = "@"  # a root value "@name" means the host value of root `name`
WRAPPER_MODE = stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH
STRICT_ENV = "CS_STRICT"  # env: "1" makes check-path exit non-zero on a miss
RESOLVE_SH = 'command -v -- "$1" >/dev/null'  # knows builtins and shell keywords too
EXIT_UNRESOLVED = 1
GENERATED_NOTE = "# generated by tools/cmdindex.py gen-bin from paths.json; do not edit"

WRAPPER = """#!/bin/sh
{note}
here=$(dirname "$(readlink -f "$0")")
target="$here/{up}/{script}"
if [ ! -f "$target" ]; then
  echo "{name}: target missing: $target (fix paths.json, run tools/cmdindex.py gen-bin)" >&2
  exit {missing}
fi
exec {runner} "$target"{args} "$@"
"""


def load(home=None) -> dict:
    return cmdnames.load(home or HOME)


def resolve(index, key, home=None) -> str:
    """Absolute path of a command's script (repo-based entries sit next to the home folder)."""
    entry = index["commands"][key]
    base = os.path.dirname(home or HOME) if entry.get("base") == BASE_REPO else (home or HOME)
    return os.path.join(base, entry["script"])


def root(index, name, side, home=None, _seen=()) -> str | None:
    """Value of a root on one side. Host values written '@home' resolve to the real home, '@other' to that root's host value, '~' and '$VAR' are expanded. A cycle of '@' refs -> None."""
    value = index["roots"][name].get(side)
    if value is None or name in _seen:
        return None
    if value == HOME_MARK:
        return home or HOME
    if value.startswith(REF_PREFIX):
        return root(index, value[len(REF_PREFIX) :], side, home, (*_seen, name))
    return os.path.expandvars(os.path.expanduser(value))


def swap(text, side, index=None, home=None) -> tuple[str, int]:
    """Replace the container root values in `text` by their `side` values; returns (text, count). Longest value first."""
    index = index or load(home)
    if side == "container":
        return text, 0
    pairs = []
    for name, r in index["roots"].items():
        new = root(index, name, side, home)
        if r.get("container") and new is not None:
            pairs.append((r["container"], new))
    if not pairs:
        return text, 0
    # one pass: a replaced value is never scanned again (a host home may contain a container value, e.g. /workspace)
    table = dict(pairs)
    pattern = re.compile("|".join(re.escape(old) for old, _ in sorted(pairs, key=lambda p: -len(p[0]))))
    text, count = pattern.subn(lambda m: table[m.group(0)], text)
    return text, count


def wrapper_text(index, key) -> str:
    entry = index["commands"][key]
    name = command_name(index, key)
    repo = entry.get("base") == BASE_REPO
    up = "../.." if repo else ".."
    args = "".join(" " + a for a in entry.get("args", []))
    return WRAPPER.format(
        note=GENERATED_NOTE, up=up, script=entry["script"], name=name, missing=EXIT_MISSING,
        runner=entry.get("runner", DEFAULT_RUNNER), args=args,
    )  # fmt: skip


def planned(index, home) -> dict[str, str]:
    """{path: text} of every wrapper that must exist: container-side commands in bin, host-only ones in bin-host."""
    out = {}
    for key, entry in commands(index).items():
        folder = BIN_DIRS["host" if side_of(entry) == "host" else "container"]
        out[os.path.join(home, folder, command_name(index, key))] = wrapper_text(index, key)
    return out


def gen_bin(home=None, check=False) -> list[str]:
    """Write the wrappers (or with check=True only compare). Returns the list of problems; empty = in sync."""
    home = home or HOME
    want = planned(load(home), home)
    problems = []
    for path, text in sorted(want.items()):
        have = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                have = f.read()
        if have != text:
            problems.append(("missing: " if have is None else "differs: ") + path)
            if not check:
                write_text(path, text)  # atomic: a hook exec'ing the wrapper never sees an empty or half-written one
        if not check:
            os.chmod(path, WRAPPER_MODE)
    for d in BIN_DIRS.values():
        folder = os.path.join(home, d)
        for fn in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
            path = os.path.join(folder, fn)
            if path not in want and _is_generated(path):  # hand-made files and folders are not ours to remove
                problems.append("stale: " + path)
                if not check:
                    os.remove(path)
    return problems


def _is_generated(path):
    """True for a regular file that carries GENERATED_NOTE (written by gen_bin)."""
    if not os.path.isfile(path):
        return False
    try:
        with open(path, encoding="utf-8") as f:
            return GENERATED_NOTE in f.read()
    except (OSError, UnicodeDecodeError):
        return False


def hook_commands(settings) -> list[str]:
    """Every hook command string in a settings.json dict."""
    out = []
    for groups in settings.get("hooks", {}).values():
        for group in groups:
            out += [h["command"] for h in group.get("hooks", []) if h.get("command")]
    return out


def resolves(word, path) -> bool:
    return subprocess.run(["sh", "-c", RESOLVE_SH, "sh", word], env={"PATH": path}, check=False).returncode == 0


def unresolved(settings_file, index, path) -> list[str]:
    """Hook commands (first word) and container-side cs-* names that do not resolve on `path`."""
    with open(settings_file, encoding="utf-8") as f:
        settings = json.load(f)
    words = []
    for cmd in hook_commands(settings):
        parts = shlex.split(cmd)
        words += [("hook", parts[0])] if parts else []
    names = [command_name(index, k) for k in commands(index, "container")]
    words += [("index", n) for n in names if n.startswith(index["prefix"])]
    return [f"{kind}: {w}" for kind, w in words if not resolves(w, path)]


def check_path(settings_file, bin_dir, home=None) -> int:
    """Print a loud warning per unresolved name; exit code 1 only when CS_STRICT=1."""
    missing = unresolved(settings_file, load(home), bin_dir + os.pathsep + os.environ.get("PATH", ""))
    for m in missing:
        print(f"WARNING cmdindex: not on PATH: {m}", file=sys.stderr)
    if missing:
        print(f"WARNING cmdindex: {len(missing)} name(s) unresolved; fix paths.json, run tools/cmdindex.py gen-bin", file=sys.stderr)
    return EXIT_UNRESOLVED if missing and os.environ.get(STRICT_ENV) == "1" else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("action", choices=["gen-bin", "check-path"])
    ap.add_argument("--settings", help="check-path: the settings.json whose hooks are checked")
    ap.add_argument("--bin", default=os.path.join(HOME, BIN_DIRS["container"]), help="check-path: wrapper folder put first on PATH")
    ap.add_argument("--check", action="store_true", help="exit 1 when the wrappers differ from the index; write nothing")
    ap.add_argument("--home", default=HOME)
    a = ap.parse_args(argv)
    if a.action == "check-path":
        return check_path(a.settings, a.bin, a.home)
    problems = gen_bin(a.home, a.check)
    for p in problems:
        print(p)
    print(f"cmdindex: {len(problems)} {'out of sync' if a.check else 'written or removed'}")
    return 1 if (a.check and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
