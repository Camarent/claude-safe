#!/usr/bin/env python3
"""swallow_scan: list every swallowed-error and broad-except handler of the non-test tool code, by package.

    python3 -I .claude/tools/audit/swallow_scan.py [--root TOOLS_DIR] [--out FILE] [--defer FILE ...]

Walks every .py under the tools folder except `tests/` (ast, no regex). One row per ExceptHandler:
- kind=swallow: body only pass / continue / return of a constant or None / `...`; no raise, no swallowed() call, no print or log call.
- kind=broad: bare except or except Exception / BaseException whose body is not only a raise and is not kind=swallow.
- Dropped: a handler for a narrower type that re-raises or calls swallowed() (it handles the error on purpose).
--defer FILE (repeatable) marks the rows of that file as deferred to phase 06.
Without --out the markdown goes to stdout; with --out it is written there."""

import argparse
import ast
import os
import sys
from typing import NamedTuple

TOOLS_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY_SUFFIX = ".py"
TESTS_DIR = "tests"
SKIP_DIRS = frozenset({TESTS_DIR, "__pycache__"})
TOP_LEVEL = "top-level"
BROAD_TYPES = frozenset({"Exception", "BaseException"})
SWALLOW_CALL = "swallowed"
LOG_CALLS = frozenset({"print", "log", "debug", "info", "warning", "error", "exception", "critical"})
KIND_SWALLOW = "swallow"
KIND_BROAD = "broad"
DEFER_NOTE = "deferred: over 900 lines, phase 06 split"
BARE = "bare"


class Site(NamedTuple):
    path: str
    line: int
    package: str
    exc: str
    kind: str


def _is_trivial(stmt):
    """pass / continue / return of a constant or None / `...`."""
    if isinstance(stmt, (ast.Pass, ast.Continue)):
        return True
    if isinstance(stmt, ast.Return):
        return stmt.value is None or isinstance(stmt.value, ast.Constant)
    return isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant) and stmt.value.value is Ellipsis


def _call_name(call):
    f = call.func
    return f.id if isinstance(f, ast.Name) else f.attr if isinstance(f, ast.Attribute) else ""


def _raises_or_swallows(body):
    for stmt in body:
        for node in ast.walk(stmt):
            if isinstance(node, ast.Raise):
                return True
            if isinstance(node, ast.Call) and _call_name(node) == SWALLOW_CALL:
                return True
    return False


def _has_log_call(body):
    return any(isinstance(node, ast.Call) and _call_name(node) in LOG_CALLS for stmt in body for node in ast.walk(stmt))


def _exc_names(type_node):
    elts = type_node.elts if isinstance(type_node, ast.Tuple) else [type_node]
    return [e.id if isinstance(e, ast.Name) else e.attr if isinstance(e, ast.Attribute) else ast.unparse(e) for e in elts]


def classify(handler):
    """-> KIND_SWALLOW, KIND_BROAD or None (not a site)."""
    body = handler.body
    if all(_is_trivial(s) for s in body) and not _raises_or_swallows(body) and not _has_log_call(body):
        return KIND_SWALLOW
    broad = handler.type is None or any(n in BROAD_TYPES for n in _exc_names(handler.type))
    if not broad:
        return None  # narrower type: a re-raise, a swallowed() call or a log only is handled on purpose
    if all(isinstance(s, ast.Raise) for s in body):
        return None
    return KIND_BROAD


def package_of(rel):
    parts = rel.split(os.sep)
    return parts[0] if len(parts) > 1 else TOP_LEVEL


def scan_tree(root):
    """-> sorted list of Site for every non-test .py under root."""
    sites = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            if not name.endswith(PY_SUFFIX):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), root)
            with open(os.path.join(root, rel), encoding="utf-8") as fh:
                tree = ast.parse(fh.read(), filename=rel)
            for node in ast.walk(tree):
                if not isinstance(node, ast.ExceptHandler):
                    continue
                kind = classify(node)
                if kind:
                    exc = BARE if node.type is None else ast.unparse(node.type)
                    sites.append(Site(rel, node.lineno, package_of(rel), exc, kind))
    return sorted(sites)


def render(sites, root, defer=()):
    """-> markdown: counts by package, then one row per site with a blank Decision column."""
    deferred = {os.path.abspath(d) for d in defer}
    packages = sorted({s.package for s in sites})
    lines = [
        "# Swallowed-error sites",
        "",
        "Generated by `.claude/tools/audit/swallow_scan.py`: all non-test tool code, every package.",
        "",
        "## Counts by package",
        "",
        "| package | swallow | broad | total |",
        "|---|---|---|---|",
    ]
    for pkg in packages:
        mine = [s for s in sites if s.package == pkg]
        n_swallow = sum(s.kind == KIND_SWALLOW for s in mine)
        lines.append(f"| {pkg} | {n_swallow} | {len(mine) - n_swallow} | {len(mine)} |")
    n_swallow = sum(s.kind == KIND_SWALLOW for s in sites)
    lines.append(f"| **all** | {n_swallow} | {len(sites) - n_swallow} | {len(sites)} |")
    lines += ["", "## Sites", "", "| file:line | package | exception | kind | note | Decision |", "|---|---|---|---|---|---|"]
    for s in sites:
        note = DEFER_NOTE if os.path.abspath(os.path.join(root, s.path)) in deferred else ""
        lines.append(f"| {s.path}:{s.line} | {s.package} | `{s.exc}` | {s.kind} | {note} | |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="list swallowed-error and broad-except handlers by package")
    ap.add_argument("--root", default=TOOLS_ROOT, help="tools folder to scan (default: the one this script sits in)")
    ap.add_argument("--out", default="", help="write the markdown report here instead of stdout")
    ap.add_argument("--defer", action="append", default=[], help="a file whose rows are marked deferred (repeatable)")
    a = ap.parse_args(argv)
    sites = scan_tree(a.root)
    text = render(sites, a.root, a.defer)
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"VERDICT: DONE\n{len(sites)} sites written to {a.out}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
