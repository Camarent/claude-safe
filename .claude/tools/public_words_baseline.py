#!/usr/bin/env python3
"""public_words_baseline: write, preview or check the public-words baseline file (the accepted hits the public-words gate allows).

    python3 -I .claude/tools/public_words_baseline.py --write|--dry-run|--check [--dir D] [--words a,b]

--write    rewrite the baseline with one key per distinct hit, sorted, under a `#` header.
--dry-run  print how many baseline lines would change; write nothing.
--check    exit 1 when a hit is not in the baseline (the same rule as the public-words gate).
--words    use these words instead of the configured public_forbidden_words setting.

The baseline path is the public_words_baseline setting (pipeline.json), repo-relative."""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pipeline import public_words
from pipeline.configuration import (
    ENV_PUBLIC_FORBIDDEN_WORDS,
    PUBLIC_FORBIDDEN_WORDS_DEFAULT,
    PUBLIC_FORBIDDEN_WORDS_KEY,
    PUBLIC_WORDS_BASELINE_DEFAULT,
    PUBLIC_WORDS_BASELINE_KEY,
    PUBLIC_WORDS_SKIP_FILES_DEFAULT,
    PUBLIC_WORDS_SKIP_FILES_KEY,
    project,
    repo_dir,
)

HEADER = [
    "# public-words baseline: accepted hits, one key per line: file TAB word TAB line text stripped.",
    "# Generated by .claude/tools/public_words_baseline.py --write; blank and # lines are ignored.",
]


def _words(d, override):
    """The --words list when given, else the env override (comma-separated), else the pipeline.json key, else no words."""
    if override is not None:
        return [w.strip() for w in override.split(",")]
    if ENV_PUBLIC_FORBIDDEN_WORDS in os.environ:
        return [w.strip() for w in os.environ[ENV_PUBLIC_FORBIDDEN_WORDS].split(",")]
    return list(project(d).get(PUBLIC_FORBIDDEN_WORDS_KEY) or PUBLIC_FORBIDDEN_WORDS_DEFAULT)


def _keys(found):
    """-> the sorted distinct hit keys of `found` (dedupe and sort: the file is stable across scans)."""
    return sorted({public_words.hit_key(rel, w, text) for rel, _n, w, text in found})


def _content(keys):
    """-> the baseline file text: the header, then one key per line."""
    return "\n".join(HEADER + keys) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the baseline from the current hits")
    mode.add_argument("--dry-run", action="store_true", help="print how many baseline lines would change; write nothing")
    mode.add_argument("--check", action="store_true", help="exit 1 when a hit is not in the baseline")
    ap.add_argument("--dir", default=".", help="the workspace folder with pipeline.json (default: the current folder)")
    ap.add_argument("--words", default=None, help="comma-separated words, overriding the configured setting")
    a = ap.parse_args(argv)
    d = os.path.abspath(a.dir)
    repo = repo_dir(d, project(d))
    path = os.path.join(repo, project(d).get(PUBLIC_WORDS_BASELINE_KEY, PUBLIC_WORDS_BASELINE_DEFAULT))
    try:
        skip = project(d).get(PUBLIC_WORDS_SKIP_FILES_KEY, PUBLIC_WORDS_SKIP_FILES_DEFAULT)
        found = public_words.records(repo, _words(d, a.words), skip)
        baseline = public_words.read_baseline(path)
    except public_words.ScanError as e:
        print(str(e))
        return 1
    keys = _keys(found)
    if a.dry_run:
        changed = len(set(keys) ^ baseline)
        print(f"{changed} baseline lines would change in {path}")
        return 0
    if a.write:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(_content(keys))
        print(f"wrote {len(keys)} keys to {path}")
        return 0
    new, _stale = public_words.diff(found, baseline)
    for rel, n, w, text in new:
        print(f"{rel}:{n}: {w}")
        print(f"not in baseline: {public_words.hit_key(rel, w, text)}")
    print("VERDICT: " + ("FAIL" if new else "DONE"))
    return 1 if new else 0


if __name__ == "__main__":
    sys.exit(main())
